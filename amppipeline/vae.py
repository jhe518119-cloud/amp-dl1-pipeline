"""Variational autoencoder for de novo peptide generation.

The architecture follows the published description (Text S1, section S1.2):

* encoder: five one-dimensional convolutional layers mapping the one-hot
  sequence to a 50-dimensional latent space;
* decoder: four transposed convolutional layers, a 512-unit GRU, and a
  21-channel softmax output giving the amino-acid probability at each position.

The VAE is trained to reconstruct one-hot encoded peptides with a binary
cross-entropy term plus a Kullback-Leibler term. New sequences are generated by
sampling a latent vector from a standard normal distribution and decoding it.

Note
----
The original study's trained weights were not preserved. This module is a
re-implementation of the described architecture, not a recovered model. See the
repository README for the full statement.
"""

from __future__ import annotations

import json
import os
from typing import Dict, Sequence, Tuple

import numpy as np

from .constants import ALPHABET, MAX_LEN

DEFAULT_CONFIG: Dict[str, object] = {
    "max_len": MAX_LEN,
    "latent_dim": 50,
    "encoder_filters": [32, 64, 128, 128, 128],
    "decoder_start_len": 25,
    "decoder_channels": 32,
    "decoder_filters": [32, 64, 64, 64],
    "decoder_strides": [1, 2, 1, 1],
    "gru_units": 512,
    "beta": 1.0,
    "learning_rate": 1e-3,
}


def _require_tensorflow():
    try:
        import tensorflow as tf  # noqa: F401
    except ImportError as exc:  # pragma: no cover - environment dependent
        raise ImportError(
            "TensorFlow is required for model training and generation. "
            "Install it with 'pip install \"tensorflow>=2.11,<2.16\"'."
        ) from exc
    return tf


def _resolved_config(config: Dict[str, object] | None) -> Dict[str, object]:
    resolved = dict(DEFAULT_CONFIG)
    if config:
        unknown = set(config) - set(resolved)
        if unknown:
            raise ValueError("unknown VAE config keys: %s" % ", ".join(sorted(unknown)))
        resolved.update(config)
    return resolved


def build_vae(config: Dict[str, object] | None = None):
    """Build the VAE and its decoder.

    Returns ``(vae, decoder, config)``. ``vae`` maps one-hot peptides to
    reconstructed one-hot probabilities and carries the training loss; the
    ``decoder`` maps latent vectors to the same output and is used for
    generation.
    """
    tf = _require_tensorflow()
    from tensorflow import keras
    from tensorflow.keras import layers

    config = _resolved_config(config)
    max_len = int(config["max_len"])
    latent_dim = int(config["latent_dim"])
    encoder_filters: Sequence[int] = config["encoder_filters"]  # type: ignore[assignment]
    decoder_start_len = int(config["decoder_start_len"])
    decoder_channels = int(config["decoder_channels"])
    decoder_filters: Sequence[int] = config["decoder_filters"]  # type: ignore[assignment]
    decoder_strides: Sequence[int] = config["decoder_strides"]  # type: ignore[assignment]
    gru_units = int(config["gru_units"])
    beta = float(config["beta"])

    if len(decoder_filters) != len(decoder_strides):
        raise ValueError("decoder_filters and decoder_strides must have equal length")
    upsampling = int(np.prod(decoder_strides))
    if decoder_start_len * upsampling != max_len:
        raise ValueError(
            "decoder_start_len (%d) x product(decoder_strides) (%d) must equal "
            "max_len (%d)" % (decoder_start_len, upsampling, max_len)
        )

    class Sampling(layers.Layer):
        """Reparameterization trick: z = mean + exp(0.5 * log_var) * epsilon."""

        def call(self, inputs):
            z_mean, z_log_var = inputs
            epsilon = tf.random.normal(tf.shape(z_mean))
            return z_mean + tf.exp(0.5 * z_log_var) * epsilon

    inputs = keras.Input(shape=(max_len, len(ALPHABET)), name="one_hot")
    hidden = inputs
    for index, filters in enumerate(encoder_filters):
        hidden = layers.Conv1D(
            int(filters),
            kernel_size=5,
            padding="same",
            activation="relu",
            name="encoder_conv_%d" % (index + 1),
        )(hidden)
    hidden = layers.Flatten(name="encoder_flatten")(hidden)
    z_mean = layers.Dense(latent_dim, name="z_mean")(hidden)
    z_log_var = layers.Dense(latent_dim, name="z_log_var")(hidden)
    z = Sampling(name="sampling")([z_mean, z_log_var])

    decoder_input = keras.Input(shape=(latent_dim,), name="latent")
    hidden = layers.Dense(
        decoder_start_len * decoder_channels,
        activation="relu",
        name="decoder_dense",
    )(decoder_input)
    hidden = layers.Reshape(
        (decoder_start_len, decoder_channels), name="decoder_reshape"
    )(hidden)
    for index, (filters, stride) in enumerate(zip(decoder_filters, decoder_strides)):
        hidden = layers.Conv1DTranspose(
            int(filters),
            kernel_size=5,
            strides=int(stride),
            padding="same",
            activation="relu",
            name="decoder_deconv_%d" % (index + 1),
        )(hidden)
    hidden = layers.GRU(
        gru_units, return_sequences=True, name="decoder_gru"
    )(hidden)
    decoder_outputs = layers.Dense(
        len(ALPHABET), activation="softmax", name="amino_acid_probabilities"
    )(hidden)

    decoder = keras.Model(decoder_input, decoder_outputs, name="vae_decoder")
    # Connect the decoder to the sampled latent vector; without this call the
    # decoder graph would remain attached to its own `latent` input and the VAE
    # graph would be disconnected.
    reconstruction = decoder(z)
    vae = keras.Model(inputs, reconstruction, name="vae")

    # Reconstruction and KL terms. The reconstruction term is the sum of
    # per-position binary cross-entropies; the KL term is summed over latent
    # dimensions. Both are averaged over the batch. Keras backend ops are used
    # rather than raw tf ops so that the expressions accept symbolic
    # KerasTensors on Keras 2.x.
    from tensorflow.keras import backend as K

    reconstruction_loss = K.sum(
        K.binary_crossentropy(inputs, reconstruction), axis=-1
    )
    kl_divergence = -0.5 * K.sum(
        1.0 + z_log_var - K.square(z_mean) - K.exp(z_log_var), axis=-1
    )
    vae.add_loss(K.mean(reconstruction_loss + beta * kl_divergence))
    vae.add_metric(K.mean(reconstruction_loss), name="reconstruction")
    vae.add_metric(K.mean(kl_divergence), name="kl")
    vae.compile(optimizer=keras.optimizers.Adam(learning_rate=float(config["learning_rate"])))
    return vae, decoder, config


def save_vae(vae, config: Dict[str, object], weights_path: str) -> str:
    """Save weights and the architecture config next to each other."""
    directory = os.path.dirname(weights_path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    vae.save_weights(weights_path)
    config_path = os.path.splitext(weights_path)[0] + ".config.json"
    with open(config_path, "w", encoding="utf-8") as handle:
        json.dump(config, handle, indent=2, sort_keys=True)
        handle.write("\n")
    return config_path


def load_vae(weights_path: str, config_path: str | None = None):
    """Rebuild the VAE from its config and load saved weights."""
    if config_path is None:
        config_path = os.path.splitext(weights_path)[0] + ".config.json"
    with open(config_path, "r", encoding="utf-8") as handle:
        config = json.load(handle)
    vae, decoder, config = build_vae(config)
    vae.load_weights(weights_path)
    return vae, decoder, config


def sample_latent(n: int, latent_dim: int, seed: int | None = None) -> np.ndarray:
    """Draw ``n`` latent vectors from a standard normal distribution."""
    rng = np.random.default_rng(seed)
    return rng.standard_normal((n, latent_dim)).astype(np.float32)
